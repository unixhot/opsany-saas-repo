def error(error_info=ErrorStatusCode.INVALID_REQUEST, errors=None, custom_message=None, language=DEFAULT_LANGUAGE):
    http_code, error_code, error_msg = error_info.value
    params = {
        'code': http_code,
        'message': get_language_message(error_msg, language=language),
        'errcode': error_code,
    }
    if errors:
        params['errors'] = errors
    if custom_message:
        params['message'] = get_language_message(custom_message, language=language)
    return params


